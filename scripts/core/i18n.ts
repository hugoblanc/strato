/**
 * The words the person served reads: board, panel, CLI output meant for a human. One dictionary per locale,
 * chosen by `settings().ui.locale` ("en" by default, "fr" available).
 *
 * Convention, for anyone migrating a string:
 * - Key = `<area>.<element>[.<detail>]`, lowercase segments, camelCase inside a segment:
 *   `board.bloc.attend.title`, `board.header.refresh.tip`. Areas: `board`, `panel`, `cli`, `master`, `task` (notes written on a task),
 *   `provider` (the labels, settings and words of the built-in providers, `provider.<id>.…`).
 *   The suffix `.tip` is a tooltip (title attribute), `.empty` an empty state, `.title` a heading.
 * - Add the key to `en` first (it defines the type), then to `fr`: the typecheck refuses a missing French key,
 *   and i18n.test.ts refuses any key present in one dictionary and not the other.
 * - Variables are `{name}` in the text and `t("key", { name })` at the call site. Never build a sentence by
 *   concatenating two translated fragments: word order differs between languages, give the whole sentence a key.
 * - Plurals: two keys (`….one`, `….other`) chosen at the call site, not a suffix glued in code.
 * - Strings needed by the board's client-side script live under `board.js.`: `clientMessages()` ships them to the page
 *   as `window.STRATO_I18N`, and the script reads them with `tr("board.js.…")`.
 * - Not translated: prompts sent to Claude sessions (policy templates, in English, overridable per profile),
 *   lines for the master (it reads English), identifiers, CLI flags, and the product name "Strato".
 */
