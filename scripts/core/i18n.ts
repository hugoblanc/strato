export const DICTIONARIES: Record<Locale, Record<MessageKey, string>> = { en, fr };

/** The locale of the profile; anything unknown reads as English. */
export function locale(): Locale {
  const l = settings().ui.locale;
  return LOCALES.includes(l) ? l : "en";
}

/** The text of `key` in the profile's locale, with `{name}` replaced by `vars.name`. An unknown variable stays visible. */
export function t(key: MessageKey, vars: Record<string, string | number> = {}): string {
  const text = DICTIONARIES[locale()][key] ?? en[key];
  return text.replace(/\{(\w+)\}/g, (m, v: string) => (v in vars ? String(vars[v]) : m));
}

/** The `board.js.*` strings of the current locale, for the board's client-side script. */
export function clientMessages(): Record<string, string> {
  const dict = DICTIONARIES[locale()];
  return Object.fromEntries(Object.entries(dict).filter(([k]) => k.startsWith("board.js.")));
}
